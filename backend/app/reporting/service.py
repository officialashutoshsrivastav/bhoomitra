def _meta_rows(report: Report, user: Optional[User], sources: List[Dict[str, Any]]) -> List[List[Any]]:
    rows = [["Report", report.title], ["Type", report.report_type], ["Generated at", datetime.now(timezone.utc).isoformat()], ["Generated by", user.full_name if user else "system"], ["Methodology", report.methodology or ""], ["Disclaimer", DISCLAIMER]]
    for s in sources:
        rows.append(["Source", f"{s.get('type')}: {s.get('label')} {s.get('id') or ''}".strip()])
    return rows


def render_csv(report: Report, user: Optional[User], sections: List[Dict[str, Any]], sources: List[Dict[str, Any]]) -> bytes:
    buf = io.StringIO()
    w = csv.writer(buf)
    for r in _meta_rows(report, user, sources):
        w.writerow(r)
    for sec in sections:
        w.writerow([])
        w.writerow([f"## {sec['title']}"])
        w.writerow(sec["columns"])
        for row in sec["rows"]:
            w.writerow(row)
        if sec.get("notes"):
            w.writerow([f"Notes: {sec['notes']}"])
    return buf.getvalue().encode("utf-8-sig")


def render_xlsx(report: Report, user: Optional[User], sections: List[Dict[str, Any]], sources: List[Dict[str, Any]]) -> bytes:
    import openpyxl
    from openpyxl.styles import Font, PatternFill
    from openpyxl.utils import get_column_letter

    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "About"
    for r in _meta_rows(report, user, sources):
        ws.append(r)
    ws.column_dimensions["A"].width = 18
    ws.column_dimensions["B"].width = 100
    for i, sec in enumerate(sections, start=1):
        safe_title = re.sub(r"[\\/*?:\[\]]", "-", f"{i:02d} {sec['title']}")[:31]
        sheet = wb.create_sheet(title=safe_title)
        sheet.append([sec["title"]])
        sheet["A1"].font = Font(bold=True, size=12)
        sheet.append(sec["columns"])
        for cell in sheet[2]:
            cell.font = Font(bold=True, color="FFFFFF")
            cell.fill = PatternFill("solid", fgColor="1F5F3F")
        for row in sec["rows"]:
            sheet.append([("" if v is None else v) for v in row])
        if sec.get("notes"):
            sheet.append([])
            sheet.append([f"Notes: {sec['notes']}"])
        for col in range(1, len(sec["columns"]) + 1):
            sheet.column_dimensions[get_column_letter(col)].width = 22
        sheet.freeze_panes = "A3"
    out = io.BytesIO()
    wb.save(out)
    return out.getvalue()


def render_pdf(report: Report, user: Optional[User], sections: List[Dict[str, Any]], sources: List[Dict[str, Any]]) -> bytes:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4, landscape
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import PageBreak, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=landscape(A4), leftMargin=14 * mm, rightMargin=14 * mm, topMargin=14 * mm, bottomMargin=14 * mm, title=report.title, author="Bhoomitra")
    styles = getSampleStyleSheet()
    small = ParagraphStyle("small", parent=styles["BodyText"], fontSize=7.5, leading=9.5)
    h1 = ParagraphStyle("h1", parent=styles["Title"], fontSize=16, textColor=colors.HexColor("#1F5F3F"))
    story = [Paragraph(report.title, h1), Paragraph("Bhoomitra — Department of Land Resources, Ministry of Rural Development (PME Division)", styles["BodyText"]), Spacer(1, 6)]
    meta = Table([[Paragraph(str(a), small), Paragraph(str(b), small)] for a, b in _meta_rows(report, user, sources)], colWidths=[35 * mm, 225 * mm])
    meta.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.25, colors.grey), ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#E8F1EC")), ("VALIGN", (0, 0), (-1, -1), "TOP")]))
    story += [meta, Spacer(1, 10)]
    for sec in sections:
        story.append(Paragraph(sec["title"], styles["Heading2"]))
        rows = [sec["columns"]] + [[("" if v is None else v) for v in r] for r in sec["rows"][:400]]
        data = [[Paragraph(str(c)[:400], small) for c in r] for r in rows]
        ncols = max(1, len(sec["columns"]))
        table = Table(data, colWidths=[(269 * mm) / ncols] * ncols, repeatRows=1)
        table.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.25, colors.grey), ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1F5F3F")), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white), ("VALIGN", (0, 0), (-1, -1), "TOP"), ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F4F8F5")])]))
        story.append(table)
        if len(sec["rows"]) > 400:
            story.append(Paragraph(f"… {len(sec['rows']) - 400} more rows omitted from PDF; use CSV/XLSX for full export.", small))
        if sec.get("notes"):
            story.append(Paragraph(f"Notes: {sec['notes']}", small))
        story.append(Spacer(1, 8))
    story.append(Paragraph(DISCLAIMER, small))
    doc.build(story)
    return buf.getvalue()


RENDERERS = {"csv": (render_csv, "text/csv"), "xlsx": (render_xlsx, "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"), "pdf": (render_pdf, "application/pdf")}


