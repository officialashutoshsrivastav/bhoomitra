def create_report(db: Session, *, title: str, report_type: str, fmt: str, params: Dict[str, Any], methodology: Optional[str], user: User, background: bool = True) -> Tuple[Report, Optional[BackgroundJob]]:
    if report_type not in BUILDERS:
        raise ValidationFailed(f"report_type must be one of {REPORT_TYPES}")
    if fmt not in RENDERERS:
        raise ValidationFailed(f"format must be one of {FORMATS}")
    report = Report(title=title, report_type=report_type, format=fmt, parameters=params, methodology=methodology, status="queued", created_by=user.id)
    db.add(report)
    db.commit()
    if background:
        job = enqueue(db, "report.generate", target_type="report", target_id=report.id, payload={"report_id": str(report.id)}, created_by=user.id, max_retries=1)
        return report, job
    generate(db, report.id)
    db.refresh(report)
    return report, None


def generate(db: Session, report_id: uuid.UUID) -> Report:
    report = db.get(Report, report_id)
    if not report:
        raise NotFoundError("Report not found")
    user = db.get(User, report.created_by)
    report.status = "running"
    db.commit()
    try:
        sections, sources = BUILDERS[report.report_type](db, report.parameters or {})
        renderer, mime = RENDERERS[report.format]
        data = renderer(report, user, sections, sources)
        key = build_key(f"reports/{report.id}", f"{report.report_type}.{report.format}")
        get_storage().put(key, data, mime)
        report.storage_key = key
        report.file_size = len(data)
        report.sources = sources
        report.status = "ready"
        report.error = None
        db.commit()
    except Exception as exc:
        db.rollback()
        report = db.get(Report, report_id)
        report.status = "failed"
        report.error = str(exc)[:1000]
        db.commit()
        raise
    return report


@register_job("report.generate")
def _job_generate(db: Session, job: BackgroundJob) -> Dict[str, Any]:
    r = generate(db, uuid.UUID(str(job.payload["report_id"])))
    return {"report_id": str(r.id), "status": r.status, "size": r.file_size}


def report_dict(r: Report) -> Dict[str, Any]:
    return {"id": str(r.id), "title": r.title, "report_type": r.report_type, "format": r.format, "status": r.status, "error": r.error, "file_size": r.file_size, "parameters": r.parameters, "methodology": r.methodology, "sources": r.sources, "created_at": r.created_at.isoformat(), "download_url": f"/api/v1/reports/{r.id}/download" if r.status == "ready" else None}
