def _repository_summary(db: Session, params: Dict[str, Any]) -> Tuple[List[Dict[str, Any]], List[Dict[str, Any]]]:
    docs = db.execute(select(Document.document_type, Document.status, func.count()).where(Document.deleted_at.is_(None)).group_by(Document.document_type, Document.status)).all()
    datasets = db.execute(select(Dataset.category, Dataset.status, func.count()).where(Dataset.deleted_at.is_(None)).group_by(Dataset.category, Dataset.status)).all()
    policies = db.execute(select(Policy.policy_area, Policy.status, func.count()).where(Policy.deleted_at.is_(None)).group_by(Policy.policy_area, Policy.status)).all()
    recent = db.scalars(select(Document).where(Document.status == DocumentStatus.PUBLISHED, Document.deleted_at.is_(None)).order_by(Document.published_at.desc().nullslast()).limit(25)).all()
    sections = [
        {"title": "Documents by type and status", "columns": ["Document type", "Status", "Count"], "rows": [[t.value, s.value, c] for t, s, c in docs]},
        {"title": "Datasets by category and status", "columns": ["Category", "Status", "Count"], "rows": [[t.value, s.value, c] for t, s, c in datasets]},
        {"title": "Policies by area and status", "columns": ["Policy area", "Status", "Count"], "rows": [[a, s.value, c] for a, s, c in policies]},
        {"title": "Recently published documents", "columns": ["Title", "Type", "Publication date", "Geography", "Demo"], "rows": [[d.title, d.document_type.value, d.publication_date.isoformat() if d.publication_date else "", d.geography or "", "yes" if d.is_demo else "no"] for d in recent]},
    ]
    return sections, [{"type": "database", "label": "Bhoomitra repository (live counts)"}]


def _dataset_export(db: Session, params: Dict[str, Any]):
    ds = db.get(Dataset, uuid.UUID(str(params.get("dataset_id"))))
    if not ds or not ds.current_version_id:
        raise NotFoundError("Dataset with a current version not found")
    stmt = select(Observation).where(Observation.dataset_version_id == ds.current_version_id)
    if params.get("variable_code"):
        stmt = stmt.where(Observation.variable_code == params["variable_code"])
    obs = db.scalars(stmt.order_by(Observation.variable_code, Observation.period_start.nullsfirst(), Observation.geography_label).limit(int(params.get("limit", 20000)))).all()
    version = db.get(DatasetVersion, ds.current_version_id)
    rows = [[o.variable_code, o.geography_label or "", o.period_start.isoformat() if o.period_start else "", o.period_end.isoformat() if o.period_end else "", o.value, o.unit or "", o.value_kind, "yes" if o.is_demo else "no"] for o in obs]
    return [{"title": f"Observations — {ds.name} (v{version.version_number})", "columns": ["Variable", "Geography", "Period start", "Period end", "Value", "Unit", "Value kind", "Demo"], "rows": rows, "notes": ds.provenance}], [{"type": "dataset_version", "id": str(version.id), "label": f"{ds.name} v{version.version_number}", "checksum": version.checksum_sha256, "license": ds.license}]


def _policy_indicators(db: Session, params: Dict[str, Any]):
    stmt = select(PolicyIndicator)
    if params.get("policy_id"):
        stmt = stmt.where(PolicyIndicator.policy_id == uuid.UUID(str(params["policy_id"])))
    if params.get("code"):
        stmt = stmt.where(PolicyIndicator.code == params["code"])
    rows = db.scalars(stmt.order_by(PolicyIndicator.code, PolicyIndicator.period_start).limit(20000)).all()
    units = {u.id: u.name for u in db.scalars(select(AdminUnit).where(AdminUnit.id.in_({r.admin_unit_id for r in rows if r.admin_unit_id}))).all()} if rows else {}
    policies = {p.id: p.title for p in db.scalars(select(Policy).where(Policy.id.in_({r.policy_id for r in rows if r.policy_id}))).all()} if rows else {}
    return [{"title": "Policy indicators", "columns": ["Policy", "Code", "Indicator", "Geography", "Period start", "Value", "Unit", "Value kind", "Demo"], "rows": [[policies.get(r.policy_id, ""), r.code, r.name, units.get(r.admin_unit_id, ""), r.period_start.isoformat() if r.period_start else "", r.value, r.unit or "", r.value_kind, "yes" if r.is_demo else "no"] for r in rows]}], [{"type": "policy_indicators", "label": f"{len(rows)} indicator records"}]


def _simulation_run(db: Session, params: Dict[str, Any]):
    run = db.get(SimulationRun, uuid.UUID(str(params.get("run_id"))))
    if not run:
        raise NotFoundError("Simulation run not found")
    sc = db.get(Scenario, run.scenario_id)
    results = db.scalars(select(SimulationResult).where(SimulationResult.run_id == run.id).order_by(SimulationResult.indicator_code, SimulationResult.year)).all()
    summary = (run.summary or {}).get("summary", {})
    sections = [
        {"title": f"Scenario: {sc.name}", "columns": ["Field", "Value"], "rows": [["Status", sc.status.value], ["Horizon (years)", sc.horizon_years], ["Interventions", str(sc.interventions)], ["Baseline source", str((sc.baseline or {}).get("source"))], ["Baseline value kind", (sc.baseline or {}).get("value_kind")], ["Iterations", run.iterations], ["Seed", run.seed], ["Demo", "yes" if sc.is_demo else "no"]]},
        {"title": "Indicator summary (base → end)", "columns": ["Indicator", "Domain", "Unit", "Base", "End (median)", "End p10", "End p90", "Change %"], "rows": [[v["label"], v["domain"], v["unit"], v["base"], v["end"], v["end_low"], v["end_high"], v["change_pct"]] for v in summary.values()]},
        {"title": "Risks", "columns": ["Domain", "Severity", "Statement", "Value kind"], "rows": [[r["domain"], r["severity"], r["statement"], r["value_kind"]] for r in (run.risks or [])]},
        {"title": "Assumptions", "columns": ["Code", "Statement", "Low", "High", "Basis"], "rows": [[a.code, a.statement, a.low, a.high, a.basis or ""] for a in sc.assumptions]},
        {"title": "Time series (MODELLED with UNCERTAINTY bands)", "columns": ["Indicator", "Year", "Value", "p10", "p90", "Value kind"], "rows": [[r.indicator_code, r.year, r.value, r.low, r.high, r.value_kind] for r in results]},
    ]
    return sections, [{"type": "simulation_run", "id": str(run.id), "label": f"Run {str(run.id)[:8]}"}, {"type": "scenario", "id": str(sc.id), "label": sc.name}, {"type": "recommendation", "id": str(run.recommendation_id) if run.recommendation_id else None, "label": "Evidence trace"}]


def _analytics_run(db: Session, params: Dict[str, Any]):
    run = db.get(AnalyticsRun, uuid.UUID(str(params.get("run_id"))))
    if not run:
        raise NotFoundError("Analytics run not found")
    res = run.result or {}
    rows: List[List[Any]] = []
    for k, v in res.items():
        if isinstance(v, (int, float, str)) or v is None:
            rows.append([k, v])
        elif isinstance(v, list) and v and isinstance(v[0], dict):
            continue
        else:
            rows.append([k, str(v)[:500]])
    sections = [{"title": f"{run.analysis_type} — {run.title}", "columns": ["Metric", "Value"], "rows": rows}]
    for k, v in res.items():
        if isinstance(v, list) and v and isinstance(v[0], dict):
            cols = list(v[0].keys())
            sections.append({"title": k, "columns": cols, "rows": [[str(item.get(c, "")) if isinstance(item.get(c), (dict, list)) else item.get(c, "") for c in cols] for item in v[:5000]]})
    return sections, [{"type": "analytics_run", "id": str(run.id), "label": run.title}, {"type": "recommendation", "id": str(run.recommendation_id) if run.recommendation_id else None, "label": "Evidence trace"}]


def _innovation_summary(db: Session, params: Dict[str, Any]):
    challenges = db.scalars(select(Challenge).where(Challenge.deleted_at.is_(None)).order_by(Challenge.created_at.desc())).all()
    counts = dict(db.execute(select(Submission.challenge_id, func.count()).group_by(Submission.challenge_id)).all())
    return [{"title": "Innovation challenges", "columns": ["Title", "Type", "Theme", "Status", "Opens", "Closes", "Submissions", "Demo"], "rows": [[c.title, c.challenge_type, c.theme or "", c.status.value, c.opens_at.date().isoformat() if c.opens_at else "", c.closes_at.date().isoformat() if c.closes_at else "", counts.get(c.id, 0), "yes" if c.is_demo else "no"] for c in challenges]}], [{"type": "database", "label": "Innovation portal"}]


